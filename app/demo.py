"""Seeds a few realistic pieces of content (all fictional) so the dashboard and queue are not empty."""
from . import db, main
from .main import Accept, Decision, Dismiss

LONG = ("Please note that all warranty claims must be submitted through the official Lumora member portal within thirty days "
        "of discovering the defect, together with proof of purchase and photographs of the affected product, otherwise they cannot be processed.")


def U(uid):
    with db.conn() as c:
        return dict(c.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone())


def _make(uid, title, kind, channel, body, fg="", bg=""):
    with db.conn() as c:
        return main.create_content(c, uid, title, kind, channel, body, fg, bg)


def _findings(cid):
    with db.conn() as c:
        return [dict(r) for r in c.execute(
            "SELECT * FROM findings WHERE content_id=? AND state='open' AND revision_id=(SELECT MAX(id) FROM revisions WHERE content_id=?)", (cid, cid))]


def _accept(uid, cid, rule_id, text=None):
    for f in _findings(cid):
        if f["rule_id"] == rule_id and (text is None or f["text"].lower() == text.lower()):
            main.accept(f["id"], Accept(), U(uid))
            return


def _accept_all(uid, cid, rule_id):
    for _ in range(10):
        fs = [f for f in _findings(cid) if f["rule_id"] == rule_id and f["fix"] != "null"]
        if not fs:
            return
        try:
            main.accept(fs[0]["id"], Accept(), U(uid))
        except Exception:
            return


def _dismiss(uid, cid, rule_id, reason):
    for f in _findings(cid):
        if f["rule_id"] == rule_id:
            main.dismiss(f["id"], Dismiss(reason=reason), U(uid))


def seed_demo():
    with db.conn() as c:
        if c.execute("SELECT 1 FROM content LIMIT 1").fetchone():
            return

    # 1. Approved piece (Alex)
    a = _make("u_alex", "Lumora Hub launch post", "post", "Instagram",
              "Meet the new Lumora Hub! It connects up to 64 bulbs and works with every Lumora Smart Bulb. "
              "Our users love how calm their evenings feel. " + LONG + " Read the setup guide to get started.")
    _accept_all("u_alex", a, "BG-1.1")
    _dismiss("u_alex", a, "BG-5.3", "Legal wording, cannot be shortened")
    main.submit(a, U("u_alex"))
    main.decision(a, Decision(decision="approve", comment="Looks good, thanks."), U("u_morgan"))

    # 2. Waiting for the compliance reviewer (Sam)
    b = _make("u_sam", "Warranty + energy ad", "advertisement", "Google Ads",
              "Lumora Smart Bulbs use up to 90% less energy and our 5-year warranty is the best in the business. "
              "Hey guys, take 15% off this week. Terms apply. " + LONG)
    _accept_all("u_sam", b, "F-3")
    _accept_all("u_sam", b, "F-5")
    _accept_all("u_sam", b, "BG-1.5")
    _dismiss("u_sam", b, "BG-3.1", "Legal approved 'best warranty' wording in ticket LEG-212")
    _dismiss("u_sam", b, "BG-5.3", "Legal wording, cannot be shortened")
    main.submit(b, U("u_sam"))

    # 3. Changes requested (Sam)
    d = _make("u_sam", "Spring newsletter", "email", "Email",
              "Hi guys, our Spring Sale is on: 20% off all bulbs. Lumora was founded in 2015 and we are still growing. "
              "Terms apply. Click here to shop.")
    _accept_all("u_sam", d, "BG-1.5")
    _accept_all("u_sam", d, "F-1")
    _dismiss("u_sam", d, "F-6", "Offer is still running in the India region")
    _dismiss("u_sam", d, "BG-5.1", "Link text is generated by the email tool")
    main.submit(d, U("u_sam"))
    main.decision(d, Decision(decision="changes", comment="Spring Sale ended on 31 March (fact F-6). Please remove or replace the offer."),
                  U("u_riley"))

    # 4. Messy draft (Alex) - repeated mistakes, long sentence dismissed
    e = _make("u_alex", "Weekend promo post", "post", "Facebook",
              "HURRY!!! Our lumora Hub is the BEST way to light your home! Our cheap bulbs make users smile, guaranteed! "
              "Better than Philips Hue. Click here to shop. " + LONG, fg="#CCCCCC", bg="#FFFFFF")
    _dismiss("u_alex", e, "BG-5.3", "Legal wording, cannot be shortened")

    # 5. Support page draft (Alex)
    f = _make("u_alex", "Setup help page", "document", "Website",
              "Welcome users! Setting up your Lumora Hub takes five minutes. Awesome stuff awaits. "
              "The hub connects up to 100 bulbs. Read more.")
